var (
	moneyRe  = regexp.MustCompile(`(?i)(?:₹|inr|rs\.?)\s*([0-9][0-9,:\s]*(?:\.[0-9]+)?)`)
	numberRe = regexp.MustCompile(`(?i)([0-9]+(?:\.[0-9]+)?)\s*%`)
	monthsRe = regexp.MustCompile(`(?i)([0-9]+)\s*months?`)
)

type Evidence struct {
	Source   string `json:"source"`
	Excerpt  string `json:"excerpt"`
	Original string `json:"original"`
	Currency string `json:"currency,omitempty"`
	Period   string `json:"period,omitempty"`
	Formula  string `json:"formula,omitempty"`
}

type Field struct {
	Value       any        `json:"value"`
	Status      string     `json:"status"` // explicit | derived | missing | ambiguous
	Explanation string     `json:"explanation,omitempty"`
	Evidence    []Evidence `json:"evidence,omitempty"`
}

type Result struct {
	Fields   map[string]Field `json:"fields"`
	Warnings []string         `json:"warnings,omitempty"`
}

type sourceLine struct {
	Ref  string
	Text string
}

type SourceLine struct {
	Ref  string
	Text string
}

func SourceText(ctx context.Context, filename string, b []byte) ([]SourceLine, error) {
	lines, err := sourceLines(ctx, filename, b)
	if err != nil {
		return nil, err
	}
	out := make([]SourceLine, len(lines))
	for i, line := range lines {
		out[i] = SourceLine{Ref: line.Ref, Text: line.Text}
	}
	return out, nil
}

func Extract(ctx context.Context, filename string, b []byte) (Result, error) {
	lines, err := sourceLines(ctx, filename, b)
	if err != nil {
		return Result{}, err
	}
	if len(lines) == 0 {
		return Result{}, fmt.Errorf("document contains no readable text")
	}
	fields := map[string]Field{}
	for _, name := range []string{"id", "task", "setup_cost_inr", "annual_benefit_inr", "annual_running_cost_inr", "benefit_type", "overlap_group", "adoption_pct", "readiness", "ramp_months", "delay_months"} {
		fields[name] = Field{Value: nil, Status: "missing", Explanation: "The document does not state this field explicitly."}
	}
	for _, line := range lines {
		lower := strings.ToLower(line.Text)
		assignText(fields, "id", line, lower, []string{"id", "pilot id", "proposal id"})
		assignText(fields, "task", line, lower, []string{"task", "use case", "business process"})
		assignMoney(fields, "setup_cost_inr", line, lower, []string{"setup", "implementation", "one-time", "integration"})
		assignMoney(fields, "annual_benefit_inr", line, lower, []string{"annual benefit", "annual savings", "benefit per year"})
		assignMoney(fields, "annual_running_cost_inr", line, lower, []string{"annual running", "annual operating", "recurring", "subscription"})
		assignPercent(fields, "adoption_pct", line, lower, []string{"adoption"})
		assignMonths(fields, "ramp_months", line, lower, []string{"ramp", "ramp-up"})
		assignMonths(fields, "delay_months", line, lower, []string{"delay", "go-live delay"})
		for _, value := range []string{"cashable", "cashable assumption", "time freed", "non-cashable", "unknown"} {
			if strings.Contains(lower, value) && containsAny(lower, []string{"benefit type", "benefit", "saving"}) {
				fields["benefit_type"] = explicit(value, line, value)
			}
		}
		for _, value := range []string{"low", "medium", "high"} {
			if strings.Contains(lower, "readiness") && strings.Contains(lower, value) {
				fields["readiness"] = explicit(value, line, value)
			}
		}
		if strings.Contains(lower, "overlap") {
			parts := strings.SplitN(line.Text, ":", 2)
			if len(parts) == 2 && strings.TrimSpace(parts[1]) != "" {
				value := strings.TrimSpace(parts[1])
				if len([]rune(value)) <= 40 {
					fields["overlap_group"] = explicit(value, line, value)
				} else {
					fields["overlap_group"] = ambiguous("The overlap group is longer than the accepted 40 characters.", line)
				}
			} else {
				fields["overlap_group"] = ambiguous("The document mentions overlap but does not provide a confirmed group identifier.", line)
			}
		}
	}
	if fields["id"].Status == "explicit" {
		if s, ok := fields["id"].Value.(string); ok && strings.TrimSpace(s) == "" {
			fields["id"] = missing("Identifiers are generated by the proposal workflow; confirm the proposal id.")
		}
	}
	result := Result{Fields: fields}
	raw, _ := json.Marshal(result)
	if _, err := ValidateMockResponse(raw); err != nil {
		return Result{}, fmt.Errorf("deterministic extraction validation failed: %w", err)
	}
	return result, nil
}

func sourceLines(ctx context.Context, filename string, b []byte) ([]sourceLine, error) {
	switch strings.ToLower(filepath.Ext(filename)) {
	case ".pdf":
		pages, err := docparse.ExtractText(ctx, b)
		if err != nil {
			return nil, err
		}
		var out []sourceLine
		for _, p := range pages {
			for _, line := range strings.Split(p.Text, ". ") {
				if strings.TrimSpace(line) != "" {
					out = append(out, sourceLine{Ref: fmt.Sprintf("page %d", p.Page), Text: strings.TrimSpace(line)})
				}
			}
		}
		return out, nil
	case ".docx":
		return docxLines(b)
	case ".xlsx", ".xls":
		format, err := docparse.Detect(filename, b)
		if err != nil {
			return nil, err
		}
		result, err := docparse.Convert(ctx, format, b, docparse.Options{MaxRows: 20000})
		if err != nil {
			return nil, err
		}
		var out []sourceLine
		for i, line := range strings.Split(string(result.CSV), "\n") {
			if strings.TrimSpace(line) != "" {
				ref := fmt.Sprintf("row %d", i+1)
				if i < len(result.Lines) {
					ref = sourceRef(result.Lines[i])
				}
				out = append(out, sourceLine{Ref: ref, Text: line})
			}
		}
		return out, nil
	default:
		r := csv.NewReader(bytes.NewReader(b))
		r.FieldsPerRecord = -1
		var out []sourceLine
		for i := 1; ; i++ {
			row, err := r.Read()
			if err == io.EOF {
				break
			}
			if err != nil {
				return nil, err
			}
			out = append(out, sourceLine{Ref: fmt.Sprintf("row %d", i), Text: strings.Join(row, ": ")})
		}
		return out, nil
	}
}

func docxLines(b []byte) ([]sourceLine, error) {
	zr, err := zip.NewReader(bytes.NewReader(b), int64(len(b)))
	if err != nil {
		return nil, err
	}
	for _, f := range zr.File {
		if f.Name != "word/document.xml" {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return nil, err
		}
		decoder := xml.NewDecoder(rc)
		var parts []string
		for {
			token, tokenErr := decoder.Token()
			if tokenErr == io.EOF {
				break
			}
			if tokenErr != nil {
				err = tokenErr
				break
			}
			if text, ok := token.(xml.CharData); ok {
				if value := strings.TrimSpace(string(text)); value != "" {
					parts = append(parts, value)
				}
			}
		}
		_ = rc.Close()
		if err != nil {
			return nil, err
		}
		text := strings.TrimSpace(strings.Join(parts, " "))
		if text == "" {
			return nil, fmt.Errorf("document contains no readable text")
		}
		return []sourceLine{{Ref: "document", Text: text}}, nil
	}
	return nil, fmt.Errorf("DOCX document.xml is missing")
}

func sourceRef(s docparse.Source) string {
	if s.Sheet != "" {
		return fmt.Sprintf("sheet %s row %d", s.Sheet, s.Row)
	}
	if s.Page > 0 {
		return fmt.Sprintf("page %d", s.Page)
	}
	return "document"
}

func assignText(fields map[string]Field, name string, line sourceLine, lower string, labels []string) {
	if fields[name].Status == "explicit" || !containsAny(lower, labels) {
		return
	}
	parts := strings.SplitN(line.Text, ":", 2)
	value := strings.TrimSpace(parts[len(parts)-1])
	if value == "" {
		return
	}
	fields[name] = explicit(value, line, value)
}

func assignMoney(fields map[string]Field, name string, line sourceLine, lower string, labels []string) {
	if fields[name].Status == "explicit" || !containsAny(lower, labels) {
		return
	}
	match := moneyRe.FindStringSubmatch(line.Text)
	if len(match) < 2 {
		fields[name] = ambiguous("The document labels this amount but does not state a clear INR amount.", line)
		return
	}
	value, err := strconv.ParseFloat(strings.NewReplacer(",", "", ":", "", " ", "").Replace(match[1]), 64)
	if err != nil {
		return
	}
	fields[name] = Field{Value: value, Status: "explicit", Evidence: []Evidence{ev(line, match[0])}, Explanation: "Read as an INR amount from the document."}
}

func assignPercent(fields map[string]Field, name string, line sourceLine, lower string, labels []string) {
	if fields[name].Status == "explicit" || !containsAny(lower, labels) {
		return
	}
	match := numberRe.FindStringSubmatch(line.Text)
	if len(match) < 2 {
		fields[name] = ambiguous("The document mentions adoption or coverage without a clear percentage.", line)
		return
	}
	value, _ := strconv.ParseFloat(match[1], 64)
	if value < 0 || value > 100 {
		fields[name] = ambiguous("The stated percentage is outside the accepted 0–100 range.", line)
		return
	}
	fields[name] = Field{Value: value, Status: "explicit", Evidence: []Evidence{ev(line, match[0])}}
}

func assignMonths(fields map[string]Field, name string, line sourceLine, lower string, labels []string) {
	if fields[name].Status == "explicit" || !containsAny(lower, labels) {
		return
	}
	match := monthsRe.FindStringSubmatch(line.Text)
	if len(match) < 2 {
		fields[name] = ambiguous("The document mentions timing without a clear whole-month value.", line)
		return
	}
	value, _ := strconv.Atoi(match[1])
	if value > 120 {
		fields[name] = ambiguous("The stated month value is outside the accepted 0–120 range.", line)
		return
	}
	fields[name] = Field{Value: value, Status: "explicit", Evidence: []Evidence{ev(line, match[0])}}
}

func containsAny(s string, labels []string) bool {
	for _, label := range labels {
		if strings.Contains(s, label) {
			return true
		}
	}
	return false
}
func explicit(value string, line sourceLine, original string) Field {
	return Field{Value: value, Status: "explicit", Evidence: []Evidence{ev(line, original)}}
}
func missing(explanation string) Field {
	return Field{Value: nil, Status: "missing", Explanation: explanation}
}
func ambiguous(explanation string, line sourceLine) Field {
	return Field{Value: nil, Status: "ambiguous", Explanation: explanation, Evidence: []Evidence{ev(line, "")}}
}
func ev(line sourceLine, original string) Evidence {
	return Evidence{Source: line.Ref, Excerpt: line.Text, Original: original}
}
