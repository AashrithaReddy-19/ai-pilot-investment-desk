"""Regenerate contracts/engine/ from the live engine (deterministic: same code, same files).

    cd decision-engine && ./venv/bin/python scripts/build_contracts.py

For every endpoint in scripts/contract_tools.EXAMPLES it writes
    contracts/engine/<name>/request.json   the example request (method, path, body)
    contracts/engine/<name>/response.json  the engine's answer (or response.md / response.csv for text)
    contracts/engine/<name>/schema.json    JSON Schema inferred from the answer (extra keys allowed)
plus contracts/engine/INDEX.md. Run it after any intended output change, bump RULES_VERSION,
and add a CHANGELOG line; tests/test_contracts.py fails until the files match the engine.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from fastapi.testclient import TestClient  # noqa: E402

from app.main import app  # noqa: E402
from app.version import CONTRACT_VERSION, RULES_VERSION  # noqa: E402
from scripts.contract_tools import ENGINE, CONTRACTS, EXAMPLES, call, infer  # noqa: E402

TEXT_EXT = {"text/csv": "csv", "text/markdown": "md", "text/plain": "txt"}


def dump(path: Path, obj) -> None:
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False, sort_keys=False) + "\n")


def main() -> None:
    client = TestClient(app)
    ENGINE.mkdir(parents=True, exist_ok=True)
    rows = []
    for name, (method, path, body, kind) in EXAMPLES.items():
        r = call(client, method, path, body)
        if r.status_code != 200:
            raise SystemExit(f"{name}: {method} {path} returned {r.status_code}: {r.text[:300]}")
        d = ENGINE / name
        d.mkdir(exist_ok=True)
        for old in d.glob("response.*"):
            old.unlink()
        dump(d / "request.json", {"method": method, "path": path, "body": body})
        ctype = r.headers.get("content-type", "").split(";")[0]
        if kind == "json":
            dump(d / "response.json", r.json())
            schema = {"$schema": "https://json-schema.org/draft/2020-12/schema",
                      "title": f"{method} {path}", **infer(r.json())}
            resp = "response.json"
        else:
            ext = TEXT_EXT.get(ctype, "txt")
            (d / f"response.{ext}").write_bytes(r.content)     # bytes: keep CSV \r\n line endings
            schema = {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": f"{method} {path}",
                      "type": "string", "contentMediaType": ctype}
            resp = f"response.{ext}"
        dump(d / "schema.json", schema)
        rows.append(f"| `{method}` | `{path}` | [{name}]({name}/) | {resp} |")
    (ENGINE / "INDEX.md").write_text(
        "# Engine contract examples\n\n"
        f"Contract version {CONTRACT_VERSION} · rules version {RULES_VERSION}. Generated by "
        "`scripts/build_contracts.py`; do not edit by hand.\n\n"
        "Each folder holds the example request, the engine's exact response and a JSON Schema inferred from it. "
        "Schemas allow extra properties (additive changes are allowed); a key listed in `required` must stay. "
        "A field that is `null` in the example may carry a value for other inputs (missing is never zero, so any "
        "field may be null).\n\n"
        "| Method | Path | Example | Response |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")
    (CONTRACTS / "VERSION").write_text(f"{CONTRACT_VERSION}\n")
    print(f"wrote {len(rows)} endpoint contracts to {ENGINE}")


if __name__ == "__main__":
    main()
